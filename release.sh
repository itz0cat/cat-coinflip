#!/usr/bin/env bash
# =============================================================================
# release.sh — Universal project bootstrap + version bump + release tool
#
# Drop this file (+ .projectrc) into ANY project folder. Nothing is hardcoded:
# project name, jar patterns, visibility, build system — all come from
# .projectrc, or are auto-detected on first run ("init").
#
# Usage:
#   ./release.sh init                 Interactive/auto setup: creates .projectrc,
#                                      inits git repo, creates GitHub repo
#   ./release.sh bump [patch|minor|major|X.Y.Z]
#                                      Bump version, commit, push, build, release
#   ./release.sh version              Print current version
#   ./release.sh set-visibility public|private
#   ./release.sh config                Show current config
#   ./release.sh help
#
# Requires: git, gh (GitHub CLI, authenticated). Optional: jq
# =============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONFIG_FILE="${SCRIPT_DIR}/.projectrc"
CMD="${1:-help}"

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
color() { printf "\033[%sm%s\033[0m\n" "$1" "$2"; }
info()  { color "36" "==> $1"; }
ok()    { color "32" "[✓] $1"; }
warn()  { color "33" "[!] $1"; }
err()   { color "31" "[✗] $1"; }
line()  { echo "=========================================================="; }

require_bin() {
    command -v "$1" >/dev/null 2>&1 || { err "'$1' is required but not installed."; exit 1; }
}

# ---------------------------------------------------------------------------
# Config load/save (simple KEY=value file, no deps)
# ---------------------------------------------------------------------------
load_config() {
    if [ -f "$CONFIG_FILE" ]; then
        # shellcheck disable=SC1090
        source "$CONFIG_FILE"
    fi
}

save_config() {
    cat > "$CONFIG_FILE" <<EOF
# .projectrc — generated by release.sh. Edit freely; nothing here is hardcoded
# back into release.sh itself.

PROJECT_NAME="${PROJECT_NAME}"
PROJECT_TYPE="${PROJECT_TYPE}"           # fabric-mod | forge-mod | node | python | rust | generic
VISIBILITY="${VISIBILITY}"               # public | private
VERSION_FILE="${VERSION_FILE}"           # file containing the version string
VERSION_KEY="${VERSION_KEY}"             # key name inside VERSION_FILE (e.g. mod_version, version)
VERSION_FORMAT="${VERSION_FORMAT}"       # properties | json | toml | plain
JAR_GLOB="${JAR_GLOB}"                   # glob for built artifacts, empty = skip
BUILD_CMD="${BUILD_CMD}"                 # command to build the project, empty = skip
GH_WORKFLOW="${GH_WORKFLOW}"             # workflow name to watch after push, empty = skip
README_PATTERNS="${README_PATTERNS}"     # semicolon-separated sed patterns for README version refs
OUTPUT_DIR="${OUTPUT_DIR}"               # where to copy final artifacts, empty = skip
EXTRA_COMMIT_FILES="${EXTRA_COMMIT_FILES}" # extra files to always include in bump commits
EOF
    ok "Saved config to $CONFIG_FILE"
}

# ---------------------------------------------------------------------------
# Auto-detection
# ---------------------------------------------------------------------------
detect_project_type() {
    if [ -f "gradle.properties" ] && grep -qi "fabric" build.gradle* 2>/dev/null; then
        echo "fabric-mod"
    elif [ -f "gradle.properties" ] && grep -qi "forge\|neoforge" build.gradle* 2>/dev/null; then
        echo "forge-mod"
    elif [ -f "package.json" ]; then
        echo "node"
    elif [ -f "pyproject.toml" ] || [ -f "setup.py" ]; then
        echo "python"
    elif [ -f "Cargo.toml" ]; then
        echo "rust"
    else
        echo "generic"
    fi
}

apply_type_defaults() {
    case "$PROJECT_TYPE" in
        fabric-mod|forge-mod)
            VERSION_FILE="${VERSION_FILE:-gradle.properties}"
            VERSION_KEY="${VERSION_KEY:-mod_version}"
            VERSION_FORMAT="${VERSION_FORMAT:-properties}"
            JAR_GLOB="${JAR_GLOB:-build/libs/*.jar}"
            BUILD_CMD="${BUILD_CMD:-./gradlew build}"
            GH_WORKFLOW="${GH_WORKFLOW:-Build ${PROJECT_NAME}}"
            ;;
        node)
            VERSION_FILE="${VERSION_FILE:-package.json}"
            VERSION_KEY="${VERSION_KEY:-version}"
            VERSION_FORMAT="${VERSION_FORMAT:-json}"
            BUILD_CMD="${BUILD_CMD:-npm run build --if-present}"
            ;;
        python)
            VERSION_FILE="${VERSION_FILE:-pyproject.toml}"
            VERSION_KEY="${VERSION_KEY:-version}"
            VERSION_FORMAT="${VERSION_FORMAT:-toml}"
            ;;
        rust)
            VERSION_FILE="${VERSION_FILE:-Cargo.toml}"
            VERSION_KEY="${VERSION_KEY:-version}"
            VERSION_FORMAT="${VERSION_FORMAT:-toml}"
            BUILD_CMD="${BUILD_CMD:-cargo build --release}"
            ;;
        *)
            VERSION_FILE="${VERSION_FILE:-VERSION}"
            VERSION_KEY="${VERSION_KEY:-}"
            VERSION_FORMAT="${VERSION_FORMAT:-plain}"
            ;;
    esac
    OUTPUT_DIR="${OUTPUT_DIR:-}"
    JAR_GLOB="${JAR_GLOB:-}"
    README_PATTERNS="${README_PATTERNS:-}"
    EXTRA_COMMIT_FILES="${EXTRA_COMMIT_FILES:-}"
    VISIBILITY="${VISIBILITY:-private}"
}

# ---------------------------------------------------------------------------
# Version read/write (format-aware, no hardcoded project names)
# ---------------------------------------------------------------------------
get_version() {
    [ -f "$VERSION_FILE" ] || { err "Version file '$VERSION_FILE' not found."; exit 1; }
    case "$VERSION_FORMAT" in
        properties)
            grep "^${VERSION_KEY}=" "$VERSION_FILE" | cut -d'=' -f2 | tr -d ' \r\n'
            ;;
        json)
            if command -v jq >/dev/null 2>&1; then
                jq -r ".${VERSION_KEY}" "$VERSION_FILE"
            else
                grep -o "\"${VERSION_KEY}\"[[:space:]]*:[[:space:]]*\"[^\"]*\"" "$VERSION_FILE" \
                    | sed -E 's/.*:\s*"([^"]*)"/\1/'
            fi
            ;;
        toml)
            grep -E "^${VERSION_KEY}[[:space:]]*=" "$VERSION_FILE" | head -1 \
                | sed -E 's/.*=\s*"([^"]*)".*/\1/'
            ;;
        plain)
            tr -d ' \r\n' < "$VERSION_FILE"
            ;;
    esac
}

set_version() {
    local new="$1"
    case "$VERSION_FORMAT" in
        properties)
            sed -i "s/^${VERSION_KEY}=.*/${VERSION_KEY}=${new}/" "$VERSION_FILE"
            ;;
        json)
            if command -v jq >/dev/null 2>&1; then
                tmp=$(mktemp)
                jq ".${VERSION_KEY} = \"${new}\"" "$VERSION_FILE" > "$tmp" && mv "$tmp" "$VERSION_FILE"
            else
                sed -i -E "s/(\"${VERSION_KEY}\"[[:space:]]*:[[:space:]]*\")[^\"]*(\")/\1${new}\2/" "$VERSION_FILE"
            fi
            ;;
        toml)
            sed -i -E "s/^(${VERSION_KEY}[[:space:]]*=[[:space:]]*\")[^\"]*(\")/\1${new}\2/" "$VERSION_FILE"
            ;;
        plain)
            echo -n "$new" > "$VERSION_FILE"
            ;;
    esac
}

bump_semver() {
    local current="$1" type="$2"
    IFS='.' read -r MAJOR MINOR PATCH <<< "$current"
    MAJOR="${MAJOR:-0}"; MINOR="${MINOR:-0}"; PATCH="${PATCH:-0}"
    case "$type" in
        major) echo "$((MAJOR+1)).0.0" ;;
        minor) echo "${MAJOR}.$((MINOR+1)).0" ;;
        patch) echo "${MAJOR}.${MINOR}.$((PATCH+1))" ;;
        *)
            if [[ "$type" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
                echo "$type"
            else
                echo "${MAJOR}.${MINOR}.$((PATCH+1))"
            fi
            ;;
    esac
}

# ---------------------------------------------------------------------------
# init — bootstrap a project folder from scratch (or adopt existing one)
# ---------------------------------------------------------------------------
cmd_init() {
    require_bin git
    require_bin gh
    line; info "Universal project init"; line

    if [ -f "$CONFIG_FILE" ]; then
        warn "$CONFIG_FILE already exists — loading it. Delete it first to start fresh."
        load_config
    fi

    read -rp "Project name [$(basename "$PWD")]: " name
    PROJECT_NAME="${name:-$(basename "$PWD")}"

    detected="$(detect_project_type)"
    read -rp "Project type (fabric-mod/forge-mod/node/python/rust/generic) [$detected]: " ptype
    PROJECT_TYPE="${ptype:-$detected}"

    apply_type_defaults

    read -rp "Version file [$VERSION_FILE]: " vf
    VERSION_FILE="${vf:-$VERSION_FILE}"
    read -rp "Version key [$VERSION_KEY]: " vk
    VERSION_KEY="${vk:-$VERSION_KEY}"
    read -rp "Build command (blank = skip) [$BUILD_CMD]: " bc
    BUILD_CMD="${bc:-$BUILD_CMD}"
    read -rp "GitHub Actions workflow name to watch on release (blank = skip) [$GH_WORKFLOW]: " wf
    GH_WORKFLOW="${wf:-$GH_WORKFLOW}"
    read -rp "Built artifact glob, e.g. build/libs/*.jar (blank = skip) [$JAR_GLOB]: " jg
    JAR_GLOB="${jg:-$JAR_GLOB}"
    read -rp "Copy final artifacts to dir (blank = skip): " od
    OUTPUT_DIR="${od:-$OUTPUT_DIR}"
    read -rp "Repo visibility public/private [${VISIBILITY:-private}]: " vis
    VISIBILITY="${vis:-${VISIBILITY:-private}}"

    save_config

    # Ensure a version file exists
    if [ ! -f "$VERSION_FILE" ] && [ "$VERSION_FORMAT" = "plain" ]; then
        echo -n "0.1.0" > "$VERSION_FILE"
        ok "Created $VERSION_FILE with 0.1.0"
    fi

    # git init
    if [ ! -d ".git" ]; then
        git init -q
        ok "git repo initialized"
    else
        ok "git repo already exists"
    fi

    # .gitignore sanity (append, don't overwrite)
    touch .gitignore
    grep -qxF ".projectrc.local" .gitignore || echo ".projectrc.local" >> .gitignore

    git add -A
    git diff --staged --quiet || git commit -q -m "chore: initial commit via release.sh init"

    # Create GitHub repo if it doesn't already have a remote
    if ! git remote get-url origin >/dev/null 2>&1; then
        info "Creating GitHub repo '${PROJECT_NAME}' (${VISIBILITY})..."
        gh repo create "${PROJECT_NAME}" --"${VISIBILITY}" --source=. --remote=origin --push
        ok "GitHub repo created and pushed"
    else
        ok "git remote 'origin' already configured: $(git remote get-url origin)"
        git push -u origin "$(git branch --show-current)" 2>/dev/null || true
    fi

    line
    ok "Init complete for '${PROJECT_NAME}' (${PROJECT_TYPE}, ${VISIBILITY})"
    echo "Config written to: $CONFIG_FILE"
    echo "Run './release.sh bump patch' to cut your first release."
    line
}

# ---------------------------------------------------------------------------
# set-visibility
# ---------------------------------------------------------------------------
cmd_set_visibility() {
    require_bin gh
    local vis="$1"
    [[ "$vis" == "public" || "$vis" == "private" ]] || { err "Use: public or private"; exit 1; }
    load_config
    gh repo edit --visibility "$vis" ${vis:+$([ "$vis" = "private" ] && echo --accept-visibility-change-consequences)}
    VISIBILITY="$vis"
    save_config
    ok "Repo visibility set to $vis"
}

# ---------------------------------------------------------------------------
# bump — the main release flow
# ---------------------------------------------------------------------------
cmd_bump() {
    require_bin git
    load_config
    [ -f "$CONFIG_FILE" ] || { err "No .projectrc found. Run './release.sh init' first."; exit 1; }
    apply_type_defaults

    local bump_type="${1:-patch}"
    local current_version new_version
    current_version="$(get_version)"
    new_version="$(bump_semver "$current_version" "$bump_type")"

    line
    info "Bumping ${PROJECT_NAME}: ${current_version} -> ${new_version}"
    line

    set_version "$new_version"

    # README version references, if configured (semicolon-separated sed exprs,
    # with {V} substituted for the new version)
    if [ -n "$README_PATTERNS" ] && [ -f "README.md" ]; then
        IFS=';' read -ra PATTERNS <<< "$README_PATTERNS"
        for pat in "${PATTERNS[@]}"; do
            expr="${pat//\{V\}/$new_version}"
            sed -i -E "$expr" README.md || warn "README pattern failed: $expr"
        done
        ok "README.md version references updated"
    fi

    # Commit + push
    local commit_files=("$VERSION_FILE")
    [ -f "README.md" ] && commit_files+=("README.md")
    if [ -n "$EXTRA_COMMIT_FILES" ]; then
        # shellcheck disable=SC2206
        extra=($EXTRA_COMMIT_FILES)
        commit_files+=("${extra[@]}")
    fi
    git add "${commit_files[@]}" 2>/dev/null || true

    if git diff --staged --quiet; then
        echo "No changes to commit."
    else
        git commit -q -m "chore: bump version to v${new_version}"
        info "Pushing to trigger CI..."
        git push origin "$(git branch --show-current)"
    fi

    # Optional local build
    if [ -n "$BUILD_CMD" ]; then
        info "Building locally: $BUILD_CMD"
        eval "$BUILD_CMD" || warn "Local build command failed/skipped"
    fi

    # Watch GH Actions workflow if configured
    if command -v gh >/dev/null 2>&1 && [ -n "$GH_WORKFLOW" ]; then
        info "Waiting for GitHub Actions workflow '${GH_WORKFLOW}'..."
        RUN_ID=$(gh run list --workflow="$GH_WORKFLOW" --limit 1 --json databaseId -q '.[0].databaseId' 2>/dev/null || true)
        if [ -n "$RUN_ID" ]; then
            gh run watch "$RUN_ID" || true
        else
            warn "No matching workflow run found to watch."
        fi
    fi

    # Download release artifacts + copy to OUTPUT_DIR
    if command -v gh >/dev/null 2>&1 && [ -n "$JAR_GLOB" ]; then
        mkdir -p dist
        gh release download "v${new_version}" --pattern "*.jar" --dir dist --clobber 2>/dev/null || true
        rm -f dist/*sources*.jar 2>/dev/null || true

        if [ -n "$OUTPUT_DIR" ] && [ -d "$OUTPUT_DIR" ]; then
            if compgen -G "dist/*.jar" > /dev/null; then
                cp dist/*.jar "$OUTPUT_DIR/"
                ok "Copied artifacts to $OUTPUT_DIR"
                ls -la "$OUTPUT_DIR"/*.jar 2>/dev/null | tail -5
            fi
        fi
    fi

    line
    ok "${PROJECT_NAME} v${new_version} release complete!"
    line
}

# ---------------------------------------------------------------------------
# misc commands
# ---------------------------------------------------------------------------
cmd_version() {
    load_config; apply_type_defaults
    get_version
}

cmd_config() {
    [ -f "$CONFIG_FILE" ] || { err "No .projectrc found. Run './release.sh init'."; exit 1; }
    cat "$CONFIG_FILE"
}

cmd_help() {
    cat <<'EOF'
release.sh — universal project bootstrap + release tool

Commands:
  init                          Set up .projectrc, git repo, GitHub repo
  bump [patch|minor|major|X.Y.Z]  Bump version, commit, push, build, release
  version                       Print current version
  set-visibility public|private Change GitHub repo visibility
  config                        Show current .projectrc
  help                          Show this message

Drop release.sh into any project folder and run 'init' — it detects the
project type (Fabric/Forge mod, Node, Python, Rust, or generic) and writes
a .projectrc with everything it needs. No project-specific names are ever
hardcoded in this script; edit .projectrc any time to adjust behavior.
EOF
}

# ---------------------------------------------------------------------------
# dispatch
# ---------------------------------------------------------------------------
case "$CMD" in
    init) cmd_init ;;
    bump) shift; cmd_bump "$@" ;;
    version) cmd_version ;;
    set-visibility) shift; cmd_set_visibility "$@" ;;
    config) cmd_config ;;
    help|--help|-h) cmd_help ;;
    *) err "Unknown command: $CMD"; cmd_help; exit 1 ;;
esac
